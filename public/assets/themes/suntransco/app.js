function toggleQuoteType(inputEl) {
    const parent = inputEl.closest('.quote-type-selector');
    if (parent) {
        const labels = parent.querySelectorAll('.type-btn');
        labels.forEach(lbl => {
            lbl.classList.remove('active');
            lbl.style.setProperty('background', 'rgba(255,255,255,0.08)', 'important');
            lbl.style.setProperty('color', '#ffffff', 'important');
        });
    }
    const current = inputEl.closest('.type-btn');
    if (current) {
        current.classList.add('active');
        current.style.setProperty('background', '#2563eb', 'important');
        current.style.setProperty('color', '#ffffff', 'important');
    }
}

function handleQuickQuote(event) {
    event.preventDefault();
    const type = document.querySelector('input[name="shipment_type"]:checked').value;
    const pol = document.getElementById('quote_pol').value;
    const pod = document.getElementById('quote_pod').value;
    
    // Tự động điền thông tin vào RFQ Modal Form
    const rfqType = document.getElementById('rfq_type');
    const rfqPol = document.getElementById('rfq_pol');
    const rfqPod = document.getElementById('rfq_pod');
    
    if (rfqType) rfqType.value = type;
    if (rfqPol) rfqPol.value = pol;
    if (rfqPod) rfqPod.value = pod;
    
    openModal('rfqModal');
}



