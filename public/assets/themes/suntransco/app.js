function switchLanguage(lang) {
    try {
        localStorage.setItem('site_lang', lang);
        document.cookie = "site_lang=" + lang + "; path=/; max-age=31536000";
    } catch(e) {}

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (langData[lang] && langData[lang][key]) {
            if (el.tagName === 'TITLE') document.title = langData[lang][key];
            else el.innerHTML = langData[lang][key];
        }
    });

    // Translate input placeholders
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (langData[lang] && langData[lang][key]) {
            el.placeholder = langData[lang][key];
        }
    });

    const viBtn = document.getElementById('lang-vi');
    const enBtn = document.getElementById('lang-en');
    if (viBtn) viBtn.classList.remove('active');
    if (enBtn) enBtn.classList.remove('active');
    const targetBtn = document.getElementById(`lang-${lang}`);
    if (targetBtn) targetBtn.classList.add('active');
    document.documentElement.lang = lang;

    // Tự động gắn tham số ngôn ngữ cho tất cả link liên kết trong trang
    updateLinkUrls(lang);
}

function getCookie(name) {
    const value = `; ${document.cookie}`;
    const parts = value.split(`; ${name}=`);
    if (parts.length === 2) return parts.pop().split(';').shift();
    return null;
}

